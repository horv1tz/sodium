#!/usr/bin/env python3
"""Generate Java sources for the Direct3D 12 interop ABI from the JSON tables produced by gen_abi.py.

usage: gen_java.py <abi-json-dir> <java-output-root> [--only structs.txt]

Output (package net.caffeinemc.mods.sodium.client.d3d12.interop.abi):
  Iids.java, Vtbl.java, Enums.java, Defines.java      and      structs/<Name>.java  (one class per C struct)
"""
import json, os, re, sys

PKG = "net.caffeinemc.mods.sodium.client.d3d12.interop.abi"
HEADER = "// GENERATED by tools/d3d12-abi (gen_abi.py + gen_java.py) from the mingw-w64 Direct3D 12 / DXGI headers. DO NOT EDIT.\n"

src, out = sys.argv[1], sys.argv[2]
only = None
if "--only" in sys.argv:
    only = set(l.strip() for l in open(sys.argv[sys.argv.index("--only") + 1]) if l.strip())

L = json.load(open(os.path.join(src, "layouts.json")))
V = json.load(open(os.path.join(src, "vtables.json")))
E = json.load(open(os.path.join(src, "enums.json")))
D = json.load(open(os.path.join(src, "defines.json")))
G = json.load(open(os.path.join(src, "guids.json")))

# windows.h structs that appear as member types (not parsed from the d3d headers)
EXTRA = {
    "RECT": {"size": 16, "align": 4, "fields": {"left": 0, "top": 4, "right": 8, "bottom": 12},
             "decl": [{"name": n, "type": "LONG", "dims": [], "kind": "plain", "offset": o} for n, o in (("left", 0), ("top", 4), ("right", 8), ("bottom", 12))]},
    "POINT": {"size": 8, "align": 4, "fields": {"x": 0, "y": 4},
              "decl": [{"name": n, "type": "LONG", "dims": [], "kind": "plain", "offset": o} for n, o in (("x", 0), ("y", 4))]},
    "LUID": {"size": 8, "align": 4, "fields": {"LowPart": 0, "HighPart": 4},
             "decl": [{"name": "LowPart", "type": "DWORD", "dims": [], "kind": "plain", "offset": 0},
                      {"name": "HighPart", "type": "LONG", "dims": [], "kind": "plain", "offset": 4}]},
    "LARGE_INTEGER": {"size": 8, "align": 8, "fields": {"QuadPart": 0},
                      "decl": [{"name": "QuadPart", "type": "INT64", "dims": [], "kind": "plain", "offset": 0}]},
}
ALIASES = {"D3D12_RECT": "RECT", "D3D12_GPU_VIRTUAL_ADDRESS": "UINT64"}
for k, v in EXTRA.items():
    L.setdefault(k, v)
L.setdefault("D3D12_RECT", L["RECT"])

PRIM = {  # C type -> (java kind, size)
    "BYTE": ("byte", 1), "UINT8": ("byte", 1), "INT8": ("byte", 1), "CHAR": ("byte", 1), "BOOLEAN": ("byte", 1),
    "UINT16": ("short", 2), "WCHAR": ("short", 2), "WORD": ("short", 2), "USHORT": ("short", 2), "SHORT": ("short", 2),
    "UINT": ("int", 4), "INT": ("int", 4), "DWORD": ("int", 4), "LONG": ("int", 4), "ULONG": ("int", 4), "UINT32": ("int", 4),
    "HRESULT": ("int", 4), "WINBOOL": ("bool", 4), "BOOL": ("bool", 4), "FLOAT": ("float", 4), "float": ("float", 4),
    "UINT64": ("long", 8), "INT64": ("long", 8), "SIZE_T": ("long", 8), "ULONG_PTR": ("long", 8), "LONG_PTR": ("long", 8),
    "LONGLONG": ("long", 8), "D3D12_GPU_VIRTUAL_ADDRESS": ("long", 8), "DXGI_USAGE": ("int", 4), "double": ("double", 8),
    "HANDLE": ("addr", 8), "HWND": ("addr", 8), "HMONITOR": ("addr", 8),
}
JAVA_LAYOUT = {"byte": "JAVA_BYTE", "short": "JAVA_SHORT_UNALIGNED", "int": "JAVA_INT_UNALIGNED", "bool": "JAVA_INT_UNALIGNED",
               "float": "JAVA_FLOAT_UNALIGNED", "long": "JAVA_LONG_UNALIGNED", "double": "JAVA_DOUBLE_UNALIGNED", "addr": "ADDRESS_UNALIGNED"}
JAVA_TYPE = {"byte": "byte", "short": "short", "int": "int", "bool": "boolean", "float": "float", "long": "long", "double": "double", "addr": "MemorySegment"}


def pascal(name):
    parts = [p for p in name.split("_") if p]
    res = ""
    for p in parts:
        if p.upper() == "DXGI":
            res += "Dxgi"
        elif p.upper() == "D3D12" or p.upper() == "D3D":
            res += p.upper()
        else:
            res += p[0].upper() + p[1:].lower() if not p.isdigit() else p
    return res


def snake_upper(name):
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name)
    s = s.replace("__", "_")
    return s.upper()


def classify(ctype, dims):
    """-> (kind, java_kind, elem_size, struct_name)"""
    if "{...}" in ctype:
        return ("nested", None, 0, None)
    t = ctype.replace("const ", "").replace("struct ", "").replace("enum ", "").strip()
    if "*" in t:
        return ("ptr", "addr", 8, None)
    if t in PRIM:
        k, sz = PRIM[t]
        return ("prim", k, sz, None)
    if t in E:
        return ("prim", "int", 4, None)
    if t in L:
        return ("struct", None, L[t]["size"], t)
    if t.endswith(" {...}"):
        return ("nested", None, 0, None)
    raise SystemExit(f"unmapped member type: {ctype}")


def emit(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


root = os.path.join(out, *PKG.split("."))

# ------------------------------------------------------------------ Iids
lines = [HEADER, f"package {PKG};\n", "import net.caffeinemc.mods.sodium.client.d3d12.interop.Guid;", "import java.lang.foreign.MemorySegment;\n",
         "/** Interface and class IDs. Each segment is a process-lifetime 16-byte GUID. */", "public final class Iids {"]
for name in sorted(G):
    jn = re.sub(r"^(IID_|CLSID_)", lambda m: m.group(1).lower().replace("_", "") if False else "", name)
    prefix = "CLSID_" if name.startswith("CLSID_") else ""
    jn = prefix + re.sub(r"^(IID_|CLSID_)", "", name)
    lines.append(f"    /** {G[name]} */")
    lines.append(f"    public static final MemorySegment {jn} = Guid.of(\"{G[name]}\");")
lines += ["", "    private Iids() {", "    }", "}", ""]
emit(os.path.join(root, "Iids.java"), "\n".join(lines))

# ------------------------------------------------------------------ Vtbl
lines = [HEADER, f"package {PKG};\n",
         "/**", " * Vtable slot indices of every COM method (IUnknown = 0..2; derived interfaces include their bases' methods).",
         " * Each constant's Javadoc is the C prototype from the Windows headers, without the leading {@code This} parameter.", " */",
         "public final class Vtbl {"]
for iface in sorted(V):
    if not V[iface]:
        continue
    lines.append(f"    /** Slots of {iface}. */")
    lines.append(f"    public static final class {iface} {{")
    for m in V[iface]:
        proto = f"{m['ret']} {m['name']}({m['params']})".replace("*/", "* /")
        lines.append(f"        /** {proto} */")
        lines.append(f"        public static final int {snake_upper(m['name'])} = {m['slot']};")
    lines.append(f"        private {iface}() {{")
    lines.append("        }")
    lines.append("    }\n")
lines += ["    private Vtbl() {", "    }", "}", ""]
emit(os.path.join(root, "Vtbl.java"), "\n".join(lines))

# ------------------------------------------------------------------ Enums
def strip_prefix(n):
    for p in ("D3D12_", "DXGI_", "D3D_"):
        if n.startswith(p):
            return n[len(p):]
    return n


def java_int_literal(v):
    if -2**31 <= v <= 2**31 - 1:
        return str(v), "int"
    if 0 <= v <= 2**32 - 1:
        return f"(int) 0x{v:X}L", "int"
    return f"0x{v:X}L" if v >= 0 else f"{v}L", "long"


lines = [HEADER, f"package {PKG};\n",
         "/** Enumerator values, evaluated by a C compiler against the Windows headers. One nested class per C enum. */",
         "public final class Enums {"]
used_enum_classes = set()
for en in sorted(E):
    vals = E[en]
    if not vals:
        continue
    names = list(vals.keys())
    toks = [n.split("_") for n in names]
    common = 0
    if len(names) > 1:
        while all(len(t) > common + 1 for t in toks) and len({t[common] for t in toks}) == 1:
            common += 1
    cls = pascal(strip_prefix(en))
    if cls in used_enum_classes:
        cls = pascal(en)
    used_enum_classes.add(cls)
    lines.append(f"    /** {en} */")
    lines.append(f"    public static final class {cls} {{")
    used = set()
    for n, v in vals.items():
        jn = "_".join(n.split("_")[common:]) if common else n
        if jn[0].isdigit():
            jn = "_" + jn
        if jn in used:
            jn = n
        used.add(jn)
        lit, jt = java_int_literal(v)
        lines.append(f"        public static final {jt} {jn} = {lit};")
    lines.append(f"        private {cls}() {{")
    lines.append("        }")
    lines.append("    }\n")
lines += ["    private Enums() {", "    }", "}", ""]
emit(os.path.join(root, "Enums.java"), "\n".join(lines))

# ------------------------------------------------------------------ Defines
lines = [HEADER, f"package {PKG};\n", "/** Numeric constants from the Windows headers (macros), evaluated by a C compiler. */", "public final class Defines {"]
for n in sorted(D):
    lit, jt = java_int_literal(D[n])
    lines.append(f"    public static final {jt} {n} = {lit};")
lines += ["", "    private Defines() {", "    }", "}", ""]
emit(os.path.join(root, "Defines.java"), "\n".join(lines))

# ------------------------------------------------------------------ structs
warnings = []
count = 0
for sname, info in sorted(L.items()):
    if sname in ("RECT", "POINT", "LUID", "LARGE_INTEGER") and False:
        continue
    if only is not None and sname not in only:
        continue
    cls = pascal(sname) if sname not in ("RECT", "POINT", "LUID", "LARGE_INTEGER") else sname[0] + sname[1:].lower() if sname != "LARGE_INTEGER" else "LargeInteger"
    if sname == "D3D12_RECT":
        continue  # alias of RECT
    body, consts = [], []
    # consistency check of plain members against the C compiler's offsets
    running = 0
    for d in info["decl"]:
        kind, jk, esz, sn = classify(d["type"], d["dims"])
        if kind == "nested":
            continue
        count_elems = 1
        for x in d["dims"]:
            count_elems *= int(x) if isinstance(x, int) else int(D.get(x, 0) or E.get(x, {}).get(x, 0))
        total = esz * count_elems
        if d["kind"] == "plain":
            if kind == "struct":
                al = L[sn]["align"]
            else:
                al = esz
            exp = (running + al - 1) // al * al
            if exp != d["offset"]:
                warnings.append(f"{sname}.{d['name']}: expected offset {exp} but compiler says {d['offset']}")
            running = d["offset"] + total
        const = snake_upper(d["name"])
        consts.append((const, d["offset"], d, kind, jk, esz, sn, count_elems, total))
    lines = [HEADER, f"package {PKG}.structs;\n", "import java.lang.foreign.MemorySegment;", "import java.lang.foreign.SegmentAllocator;",
             "import java.lang.foreign.ValueLayout;", "import java.nio.charset.StandardCharsets;\n",
             f"/** Accessors for the C struct {{@code {sname}}} ({info['size']} bytes). Offsets come from a C compiler. */",
             f"public final class {cls} {{",
             f"    public static final long SIZE = {info['size']};", f"    public static final long ALIGNMENT = {info['align']};"]
    for const, off, d, kind, jk, esz, sn, n, total in consts:
        lines.append(f"    /** {d['type']} {d['name']}{''.join('[' + str(x) + ']' for x in d['dims'])}{' (union member)' if d['kind'] == 'union' else ''} */")
        lines.append(f"    public static final long OFFSET_{const} = {off};")
    lines.append(f"\n    private {cls}() {{\n    }}\n")
    lines.append("    /** Allocates a zero-initialised instance (arena allocators zero memory). */")
    lines.append(f"    public static MemorySegment allocate(SegmentAllocator allocator) {{\n        return allocator.allocate(SIZE, ALIGNMENT);\n    }}\n")
    lines.append("    /** Allocates a zero-initialised array of instances; element i starts at {@code i * SIZE}. */")
    lines.append(f"    public static MemorySegment allocateArray(SegmentAllocator allocator, long count) {{\n        return allocator.allocate(SIZE * count, ALIGNMENT);\n    }}\n")
    for const, off, d, kind, jk, esz, sn, n, total in consts:
        fn = d["name"][0].upper() + d["name"][1:]
        arr = bool(d["dims"])
        if kind in ("prim", "ptr") and not arr:
            jt, lay = JAVA_TYPE[jk], JAVA_LAYOUT[jk]
            if jk == "bool":
                lines.append(f"    public static boolean get{fn}(MemorySegment s) {{\n        return s.get(ValueLayout.{lay}, OFFSET_{const}) != 0;\n    }}\n")
                lines.append(f"    public static void set{fn}(MemorySegment s, boolean v) {{\n        s.set(ValueLayout.{lay}, OFFSET_{const}, v ? 1 : 0);\n    }}\n")
            else:
                lines.append(f"    public static {jt} get{fn}(MemorySegment s) {{\n        return s.get(ValueLayout.{lay}, OFFSET_{const});\n    }}\n")
                lines.append(f"    public static void set{fn}(MemorySegment s, {jt} v) {{\n        s.set(ValueLayout.{lay}, OFFSET_{const}, v);\n    }}\n")
        elif kind in ("prim", "ptr") and arr:
            jt, lay = JAVA_TYPE[jk], JAVA_LAYOUT[jk]
            if jk == "bool":
                jt = "int"
            lines.append(f"    public static final int {const}_LENGTH = {n};\n")
            lines.append(f"    public static {jt} get{fn}(MemorySegment s, int index) {{\n        return s.get(ValueLayout.{lay}, OFFSET_{const} + (long) index * {esz});\n    }}\n")
            lines.append(f"    public static void set{fn}(MemorySegment s, int index, {jt} v) {{\n        s.set(ValueLayout.{lay}, OFFSET_{const} + (long) index * {esz}, v);\n    }}\n")
            if jk == "short" and d["type"] == "WCHAR":
                lines.append(f"    /** Reads the NUL-terminated UTF-16 string stored in this member. */")
                lines.append(f"    public static String get{fn}String(MemorySegment s) {{\n        return s.asSlice(OFFSET_{const}, {total}).getString(0, StandardCharsets.UTF_16LE);\n    }}\n")
            lines.append(f"    public static MemorySegment slice{fn}(MemorySegment s) {{\n        return s.asSlice(OFFSET_{const}, {total});\n    }}\n")
        elif kind == "struct":
            lines.append(f"    /** @return a view of this member inside {{@code s}}; writes go straight through to {{@code s}}. */")
            lines.append(f"    public static MemorySegment slice{fn}(MemorySegment s) {{\n        return s.asSlice(OFFSET_{const}, {total});\n    }}\n")
            if not arr:
                lines.append(f"    public static void set{fn}(MemorySegment s, MemorySegment value) {{\n        MemorySegment.copy(value, 0, s, OFFSET_{const}, {total});\n    }}\n")
        elif kind == "nested":
            pass
    lines.append("}\n")
    emit(os.path.join(root, "structs", cls + ".java"), "\n".join(lines))
    count += 1

for w in warnings:
    print("WARNING:", w)
print(f"generated: {count} struct classes, {len(G)} IIDs, {sum(1 for v in V.values() if v)} vtables, {len(E)} enums, {len(D)} defines; {len(warnings)} layout warnings")
